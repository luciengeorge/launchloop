import "server-only";
import { strToU8, zipSync, type Zippable } from "fflate";
import { IMAGE_VARIANTS, type ImageVariant } from "./image-variants";
import { renderKitImageBuffer } from "./images";
import { LIMITS, charLength, xLength } from "./limits";
import type { Kit } from "./schema";

const count = (text: string, limit: number, measure = charLength) => `${measure(text)}/${limit} chars`;

export function kitMarkdown(kit: Kit) {
  const c = kit.content;
  if (!c) throw new Error("Kit content not generated yet");
  const b = kit.brief;

  const landing = [
    `# Landing page copy: ${b.name}`,
    "",
    `## Headline (${count(c.landing.headline, LIMITS.landingHeadline)})`,
    c.landing.headline,
    "",
    `## Subheadline (${count(c.landing.subheadline, LIMITS.landingSubheadline)})`,
    c.landing.subheadline,
    "",
    `## Call to action`,
    c.landing.cta,
    "",
    `## Features`,
    ...c.landing.features.flatMap((f) => [`### ${f.title}`, f.description, ""]),
    `## SEO`,
    `- Meta title (${count(c.landing.metaTitle, LIMITS.metaTitle)}): ${c.landing.metaTitle}`,
    `- Meta description (${count(c.landing.metaDescription, LIMITS.metaDescription)}): ${c.landing.metaDescription}`,
    `- og:image: images/${IMAGE_VARIANTS.og.file}`,
  ].join("\n");

  const productHunt = [
    `# Product Hunt post: ${c.productHunt.name}`,
    "",
    `## Tagline (${count(c.productHunt.tagline, LIMITS.phTagline)})`,
    c.productHunt.tagline,
    "",
    `## Description (${count(c.productHunt.description, LIMITS.phDescription)})`,
    c.productHunt.description,
    "",
    `## Topics`,
    c.productHunt.topics.join(", "),
    "",
    `## Maker comment (post as the first comment)`,
    c.productHunt.makerComment,
    "",
    `## Gallery`,
    `Upload images/${IMAGE_VARIANTS.ph.file} first, then the other two.`,
    "",
    "> Product Hunt bans asking for upvotes. This copy asks for feedback only. Keep it that way when you edit it.",
  ].join("\n");

  const xThread = [
    `# X thread (${c.xThread.length} posts)`,
    "",
    ...c.xThread.flatMap((post, i) => [`## ${i + 1}/${c.xThread.length} (${count(post, LIMITS.xPost, xLength)})`, post, ""]),
    `Attach images/${IMAGE_VARIANTS.x.file} to post 1.`,
  ].join("\n");

  const linkedin = [`# LinkedIn post (${count(c.linkedin, LIMITS.linkedin)})`, "", c.linkedin].join("\n");

  const checklist = [`# Launch-day checklist`, "", ...(kit.checklist ?? []).map((item) => `- [ ] ${item}`)].join("\n");

  const brief = [
    `# Product brief: ${b.name}`,
    "",
    `**One-liner:** ${b.oneLiner}`,
    `**Audience:** ${b.audience}`,
    `**Problem:** ${b.problem}`,
    `**Tone:** ${b.tone}`,
    "",
    "## Features",
    ...b.features.map((f) => `- ${f}`),
    "",
    "## Proof points (from your repo and site)",
    ...(b.proofPoints.length ? b.proofPoints.map((p) => `- ${p}`) : ["- None found"]),
    "",
    "## Stack",
    b.stack.join(", ") || "Not detected",
  ].join("\n");

  return { landing, productHunt, xThread, linkedin, checklist, brief };
}

export async function buildKitZip(kit: Kit): Promise<Uint8Array> {
  const md = kitMarkdown(kit);
  const variants = Object.keys(IMAGE_VARIANTS) as ImageVariant[];
  const images = await Promise.all(variants.map((v) => renderKitImageBuffer(kit, v)));

  const readme = [
    `# ${kit.brief.name} launch kit`,
    "",
    `Generated by LaunchLoop on ${new Date(kit.generatedAt ?? Date.now()).toUTCString()}.`,
    "",
    "| File | What it is |",
    "| --- | --- |",
    "| landing-page.md | Hero, subheadline, CTA, features, meta tags |",
    "| product-hunt.md | Name, tagline, description, topics, maker comment |",
    "| x-thread.md | The launch thread, one post per section |",
    "| linkedin.md | LinkedIn launch post |",
    "| launch-checklist.md | What to do, in order, on launch day |",
    "| brief.md | The product brief everything was written from |",
    "| kit.json | Everything above as JSON |",
    ...variants.map((v) => `| images/${IMAGE_VARIANTS[v].file} | ${IMAGE_VARIANTS[v].label} |`),
    "",
    "Every limit was checked when this kit was generated. If you edit the copy, re-check lengths before posting.",
  ].join("\n");

  const files: Zippable = {
    "README.md": strToU8(readme),
    "landing-page.md": strToU8(md.landing),
    "product-hunt.md": strToU8(md.productHunt),
    "x-thread.md": strToU8(md.xThread),
    "linkedin.md": strToU8(md.linkedin),
    "launch-checklist.md": strToU8(md.checklist),
    "brief.md": strToU8(md.brief),
    "kit.json": strToU8(JSON.stringify({ brief: kit.brief, palette: kit.palette, ...kit.content, checklist: kit.checklist }, null, 2)),
    images: Object.fromEntries(variants.map((v, i) => [IMAGE_VARIANTS[v].file, [images[i], { level: 0 }]])),
  };
  return zipSync(files, { level: 6 });
}

export const zipFileName = (kit: Kit) => `${kit.brief.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "launch"}-launch-kit.zip`;
